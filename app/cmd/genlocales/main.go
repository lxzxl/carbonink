// Command genlocales converts the Electron paraglide catalogs
// (desktop/messages/{en,zh-CN}.json) into NSGo ICU catalogs.
//
// Keys become camelCase because NSGo derives one Go function per key. Existing
// keys in the output files are preserved, so the hand-written shell messages
// and their descriptions survive a regeneration.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"go.yaml.in/yaml/v3"
)

var quotedPlaceholder = regexp.MustCompile(`'\{([^{}]+)\}'`)

func main() {
	messages := flag.String("messages", "../desktop/messages", "directory with en.json and zh-CN.json")
	out := flag.String("out", "locales", "directory for en.yaml and zh-CN.yaml")
	flag.Parse()

	en, err := readCatalog(filepath.Join(*messages, "en.json"))
	if err != nil {
		fatal(err)
	}
	zh, err := readCatalog(filepath.Join(*messages, "zh-CN.json"))
	if err != nil {
		fatal(err)
	}
	if len(en) != len(zh) {
		fatal(fmt.Errorf("catalog mismatch: en has %d messages, zh-CN has %d", len(en), len(zh)))
	}
	for k := range en {
		if _, ok := zh[k]; !ok {
			fatal(fmt.Errorf("zh-CN is missing %q", k))
		}
	}

	for _, lang := range []string{"en", "zh-CN"} {
		src := en
		if lang == "zh-CN" {
			src = zh
		}
		seen := map[string]string{}
		for key := range src {
			name := camel(key)
			if prev, ok := seen[name]; ok {
				fatal(fmt.Errorf("%q and %q both become %q", prev, key, name))
			}
			seen[name] = key
		}
		path := filepath.Join(*out, lang+".yaml")
		merged, err := loadExisting(path)
		if err != nil {
			fatal(err)
		}
		added := 0
		for key, value := range src {
			name := camel(key)
			if _, exists := merged[name]; exists {
				continue
			}
			merged[name] = quotedPlaceholder.ReplaceAllString(value, "“{$1}”")
			added++
		}
		if err := writeCatalog(path, merged); err != nil {
			fatal(err)
		}
		fmt.Printf("%s: %d messages (%d new, %d preserved)\n", path, len(merged), added, len(merged)-added)
	}
}

func readCatalog(path string) (map[string]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var raw map[string]any
	if err := json.Unmarshal(data, &raw); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	out := make(map[string]string, len(raw))
	for key, value := range raw {
		if key == "$schema" {
			continue
		}
		s, ok := value.(string)
		if !ok {
			return nil, fmt.Errorf("%s: %s is not a string", path, key)
		}
		out[key] = s
	}
	return out, nil
}

func loadExisting(path string) (map[string]any, error) {
	out := map[string]any{}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return out, nil
	}
	if err != nil {
		return nil, err
	}
	if err := yaml.Unmarshal(data, &out); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return out, nil
}

func writeCatalog(path string, messages map[string]any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	// yaml.v3 sorts map keys, which keeps regeneration diffs stable.
	data, err := yaml.Marshal(messages)
	if err != nil {
		return err
	}
	header := "# Generated by cmd/genlocales from desktop/messages/*.json.\n" +
		"# Hand-written keys are preserved; edit those here, not in the JSON.\n"
	return os.WriteFile(path, append([]byte(header), data...), 0o644)
}

// camel turns activities_add_button into activitiesAddButton.
func camel(key string) string {
	parts := strings.Split(key, "_")
	var b strings.Builder
	b.WriteString(parts[0])
	for _, p := range parts[1:] {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "genlocales:", err)
	os.Exit(1)
}
