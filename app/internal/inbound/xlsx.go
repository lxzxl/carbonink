// Errors the import UI maps to its localized messages.
var (
	ErrNotTemplate        = errors.New("inbound: workbook is not a CarbonInk template")
	ErrWrongQuestionnaire = errors.New("inbound: workbook belongs to another questionnaire")
	ErrWrongPeriod        = errors.New("inbound: workbook was issued for another reporting year")
)

// RenderOptions describes one outgoing workbook.
type RenderOptions struct {
	Template        Template
	QuestionnaireID string
	SupplierName    string
	PeriodYear      int
	OrgName         string
	DueDate         string
	Positions       []string
}

// RenderBlank writes the fillable workbook: a cover sheet, one sheet per
// template group, and the very-hidden sentinel sheet the parser validates.
func RenderBlank(o RenderOptions) ([]byte, error) {
	t := o.Template
	if t.Kind == "" {
		return nil, errors.New("inbound: template is required")
	}
	f := excelize.NewFile()
	defer f.Close()
	if err := f.SetSheetName("Sheet1", coverSheet); err != nil {
		return nil, err
	}
	wrap, err := f.NewStyle(&excelize.Style{
		Alignment: &excelize.Alignment{WrapText: true, Vertical: "top"},
	})
	if err != nil {
		return nil, err
	}
	bold, err := f.NewStyle(&excelize.Style{Font: &excelize.Font{Bold: true}})
	if err != nil {
		return nil, err
	}

	if err := renderCover(f, o, wrap); err != nil {
		return nil, err
	}
	for _, sheet := range []string{"metadata", "tier1", "tier2", "tier3"} {
		questions := make([]Question, 0, 3)
		for _, q := range t.included(o.Positions) {
			if sheetOf(q.CellRef) == sheet {
				questions = append(questions, q)
			}
		}
		if len(questions) == 0 {
			continue
		}
		if err := renderQuestionSheet(f, sheet, questions, wrap, bold, o.PeriodYear); err != nil {
			return nil, err
		}
	}
	if err := renderSentinels(f, o); err != nil {
		return nil, err
	}
	f.SetActiveSheet(0)
	buf, err := f.WriteToBuffer()
	if err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func renderCover(f *excelize.File, o RenderOptions, wrap int) error {
	if err := f.SetColWidth(coverSheet, "A", "A", 90); err != nil {
		return err
	}
	if err := f.SetCellStyle(coverSheet, "A1", "A40", wrap); err != nil {
		return err
	}
	deadline := "截止日期：请尽快回复"
	deadlineEN := "Deadline: please reply at your earliest convenience"
	if strings.TrimSpace(o.DueDate) != "" {
		deadline = "截止日期：" + o.DueDate
		deadlineEN = "Deadline: " + o.DueDate
	}
	titleZH := o.Template.LabelZH
	if titleZH == "" {
		titleZH = o.Template.Kind
	}
	titleEN := o.Template.LabelEN
	if titleEN == "" {
		titleEN = o.Template.Kind
	}
	lines := []string{
		"碳排放数据采集问卷 — " + titleZH,
		"",
		fmt.Sprintf("本表由 %s 通过 CarbonInk 系统生成，用于收集贵公司报告期内（%d 年）对应的温室气体排放与活动数据。",
			o.OrgName, o.PeriodYear),
		"",
		"填写说明：",
		"1. 请优先填写 **tier1** sheet（单位产品/服务碳足迹）。如贵公司持有第三方核证报告，请将文件作为附件回传并在备注列注明文件名。",
		"2. 若无 Tier 1 数据，请填写 **tier2** sheet（公司层级分配排放），需填全 3 项（总排放、分配方法、归因排放）。",
		"3. 若前两项均不可得，可填写 **tier3** sheet（原始活动数据与计量单位），我方将使用标准排放因子进行换算。",
		"4. **metadata** sheet 中的 3 项基础信息为必填。",
		"",
		deadline,
		fmt.Sprintf("请回传至：%s 对接窗口（邮件正文中已注明）。", o.OrgName),
		"",
		"─────────────────────────────────────────────────────────────",
		"",
		"Carbon Emission Data Collection Questionnaire — " + titleEN,
		"",
		fmt.Sprintf("This workbook was generated by %s via CarbonInk to collect greenhouse-gas and activity data during reporting period %d.",
			o.OrgName, o.PeriodYear),
		"",
		"Instructions:",
		"1. Fill the **tier1** sheet first (per-unit carbon intensity). Attach any third-party verified report to your reply email and note the filename in the notes column.",
		"2. If Tier 1 is unavailable, fill the **tier2** sheet (allocated company emissions) — all three fields required.",
		"3. If neither Tier 1 nor Tier 2 is available, fill the **tier3** sheet (raw activity quantity and unit) so we can convert using standard emission factors.",
		"4. The 3 fields on the **metadata** sheet are required.",
		"",
		deadlineEN,
		fmt.Sprintf("Return to: %s (contact details in covering email).", o.OrgName),
	}
	for i, line := range lines {
		cell, err := excelize.CoordinatesToCellName(1, i+1)
		if err != nil {
			return err
		}
		if err := f.SetCellValue(coverSheet, cell, line); err != nil {
			return err
		}
	}
	return f.SetCellValue(coverSheet, "Z1", o.SupplierName)
}

func renderQuestionSheet(f *excelize.File, sheet string, questions []Question, wrap, bold int,
	periodYear int) error {
	if _, err := f.NewSheet(sheet); err != nil {
		return err
	}
	widths := map[string]float64{"A": 80, "B": 24, notesColumn: 40}
	for column, width := range widths {
		if err := f.SetColWidth(sheet, column, column, width); err != nil {
			return err
		}
	}
	for _, column := range []string{"A", notesColumn} {
		if err := f.SetCellStyle(sheet, column+"1", column+"40", wrap); err != nil {
			return err
		}
	}
	headers := map[string]string{"A1": sheetLabel(sheet), "B1": "答案 / Answer", "C1": "备注 / Notes"}
	for cell, value := range headers {
		if err := f.SetCellValue(sheet, cell, value); err != nil {
			return err
		}
	}
	if err := f.SetCellStyle(sheet, "A1", "C1", bold); err != nil {
		return err
	}
	for _, q := range questions {
		_, address := splitRef(q.CellRef)
		row, _, ok := parseAddress(address)
		if !ok {
			continue
		}
		name, err := excelize.CoordinatesToCellName(1, row)
		if err != nil {
			return err
		}
		zh, en := q.RawZH, q.RawEN
		if periodYear > 0 {
			year := strconv.Itoa(periodYear)
			zh = strings.ReplaceAll(zh, "{{period_year}}", year)
			en = strings.ReplaceAll(en, "{{period_year}}", year)
		}
		text := zh + "\n\n" + en
		if err := f.SetCellValue(sheet, name, text); err != nil {
			return err
		}
		if q.ExpectedUnit != "" {
			_ = f.AddComment(sheet, excelize.Comment{
				Cell: address, Author: "CarbonInk", Text: "单位 / Unit: " + q.ExpectedUnit,
			})
		}
		_ = f.SetRowHeight(sheet, row, 60)
	}
	return nil
}

func renderSentinels(f *excelize.File, o RenderOptions) error {
	if _, err := f.NewSheet(sentinelSheet); err != nil {
		return err
	}
	values := []struct{ key, value string }{
		{sentinelTemplateKind, o.Template.Kind},
		{sentinelVersion, o.Template.Version},
		{sentinelQuestionnaire, o.QuestionnaireID},
		{sentinelPeriod, strconv.Itoa(o.PeriodYear)},
	}
	for i, item := range values {
		keyCell, _ := excelize.CoordinatesToCellName(1, i+1)
		valueCell, _ := excelize.CoordinatesToCellName(2, i+1)
		if err := f.SetCellValue(sentinelSheet, keyCell, item.key); err != nil {
			return err
		}
		if err := f.SetCellValue(sentinelSheet, valueCell, item.value); err != nil {
			return err
		}
	}
	return f.SetSheetVisible(sentinelSheet, false, true)
}

func splitRef(cellRef string) (string, string) {
	sheet, address, ok := strings.Cut(cellRef, "!")
	if !ok {
		return "", ""
	}
	return sheet, address
}

func sheetOf(cellRef string) string {
	sheet, _ := splitRef(cellRef)
	return sheet
}

func sheetLabel(sheet string) string {
	switch sheet {
	case "metadata":
		return "基础信息 / Metadata"
	case "tier1":
		return "Tier 1：单位碳足迹 / Per-unit Carbon Intensity"
	case "tier2":
		return "Tier 2：分配排放 / Allocated Company Emissions"
	case "tier3":
		return "Tier 3：原始活动数据 / Raw Activity Data"
	}
	return sheet
}

// parseAddress reads an A1 address into a 1-based row and column.
func parseAddress(address string) (int, int, bool) {
	col, row := 0, 0
	seenDigit := false
	for _, ch := range strings.ToUpper(address) {
		switch {
		case ch >= 'A' && ch <= 'Z':
			if seenDigit {
				return 0, 0, false
			}
			col = col*26 + int(ch-'A'+1)
		case ch >= '0' && ch <= '9':
			seenDigit = true
			row = row*10 + int(ch-'0')
		default:
			return 0, 0, false
		}
	}
	if row == 0 || col == 0 {
		return 0, 0, false
	}
	return row, col, true
}

// ParsedAnswer is one template cell as the supplier left it.
type ParsedAnswer struct {
	Position   string
	Raw        string
	Number     float64
	Text       string
	UnitSuffix string
	IsNumeric  bool
	IsBlank    bool
	Note       string
}

// Warning is a soft parse issue to show next to the affected row.
type Warning struct {
	Position string
	Kind     string
	Detail   string
}

// ParseResult is the parsed workbook before it is written to the database.
type ParseResult struct {
	Answers  []ParsedAnswer
	Warnings []Warning
}

// ParseFilled validates the sentinel sheet and reads every template answer.
// Hard failures return one of the package's sentinel errors; soft issues land
// in Warnings.
func ParseFilled(data []byte, t Template, questionnaireID string, year int) (ParseResult, error) {
	var out ParseResult
	f, err := excelize.OpenReader(bytes.NewReader(data))
	if err != nil {
		return out, fmt.Errorf("inbound: open workbook: %w", err)
	}
	defer f.Close()

	index, err := f.GetSheetIndex(sentinelSheet)
	if err != nil || index < 0 {
		return out, ErrNotTemplate
	}
	read := func(row int) string {
		cell, _ := excelize.CoordinatesToCellName(2, row)
		value, _ := f.GetCellValue(sentinelSheet, cell)
		return strings.TrimSpace(value)
	}
	version := read(2)
	if read(1) != t.Kind || (version != t.Version && version != LegacyTemplateVersion) {
		return out, fmt.Errorf("%w: template %s@%s", ErrNotTemplate, read(1), version)
	}
	if read(3) != questionnaireID {
		return out, fmt.Errorf("%w: %s", ErrWrongQuestionnaire, read(3))
	}
	period, err := strconv.Atoi(read(4))
	if err != nil || period != year {
		return out, fmt.Errorf("%w: %s", ErrWrongPeriod, read(4))
	}

	tierNumerical := false
	for _, q := range t.Questions {
		sheet, address := splitRef(q.CellRef)
		if sheet == "" || address == "" {
			continue
		}
		answer := ParsedAnswer{Position: q.Position}
		sheetIndex, err := f.GetSheetIndex(sheet)
		if err != nil || sheetIndex < 0 {
			out.Answers = append(out.Answers, withBlank(answer))
			continue
		}
		raw, _ := f.GetCellValue(sheet, address)
		answer.Raw = raw
		answer.Note = readNote(f, sheet, address)
		if strings.TrimSpace(raw) == "" {
			out.Answers = append(out.Answers, withBlank(answer))
			continue
		}
		if q.Kind != "numerical" {
			answer.Text = strings.TrimSpace(raw)
			out.Answers = append(out.Answers, answer)
			continue
		}
		number, suffix, ok := leadingNumber(raw)
		if !ok {
			out.Answers = append(out.Answers, answer)
			out.Warnings = append(out.Warnings, Warning{
				Position: q.Position, Kind: "numerical_unparseable",
				Detail: fmt.Sprintf("Could not parse %q as a number.", strings.TrimSpace(raw)),
			})
			continue
		}
		answer.Number, answer.IsNumeric, answer.UnitSuffix = number, true, suffix
		if q.Tier > 0 {
			tierNumerical = true
		}
		if suffix != "" && q.ExpectedUnit != "" && q.Tier != 3 && !sameUnit(suffix, q.ExpectedUnit) {
			out.Warnings = append(out.Warnings, Warning{
				Position: q.Position, Kind: "unit_unrecognized",
				Detail: fmt.Sprintf("Unit %q does not match expected %q.", suffix, q.ExpectedUnit),
			})
		}
		out.Answers = append(out.Answers, answer)
	}
	if !tierNumerical {
		out.Warnings = append(out.Warnings, Warning{
			Kind: "blank_template",
			Detail: "No Tier 1, Tier 2, or Tier 3 numerical answer was filled — " +
				"the supplier returned no actionable data.",
		})
	}
	return out, nil
}

func withBlank(a ParsedAnswer) ParsedAnswer {
	a.IsBlank = true
	return a
}

func readNote(f *excelize.File, sheet, address string) string {
	digits := strings.IndexFunc(address, func(r rune) bool { return r >= '0' && r <= '9' })
	if digits < 0 {
		return ""
	}
	value, _ := f.GetCellValue(sheet, notesColumn+address[digits:])
	return strings.TrimSpace(value)
}

// leadingNumber pulls the number off the front of a cell, tolerating thousands
// separators and a trailing unit.
func leadingNumber(raw string) (float64, string, bool) {
	text := strings.TrimSpace(raw)
	end := 0
	seenDigit, seenDot := false, false
	for i, ch := range text {
		switch {
		case ch == '+' || ch == '-':
			if i != 0 {
				end = i
				goto done
			}
		case ch >= '0' && ch <= '9':
			seenDigit = true
		case ch == ',':
			if !seenDigit {
				goto done
			}
		case ch == '.':
			if seenDot {
				goto done
			}
			seenDot = true
		default:
			goto done
		}
		end = i + 1
	}
done:
	if !seenDigit {
		return 0, "", false
	}
	number, err := strconv.ParseFloat(strings.ReplaceAll(text[:end], ",", ""), 64)
	if err != nil || math.IsNaN(number) || math.IsInf(number, 0) {
		return 0, "", false
	}
	return number, strings.TrimSpace(text[end:]), true
}

func sameUnit(after, expected string) bool {
	normalize := func(s string) string {
		return strings.ToLower(strings.ReplaceAll(strings.ReplaceAll(s, " ", ""), "　", ""))
	}
	a, b := normalize(after), normalize(expected)
	return a == b || strings.Contains(a, b) || strings.Contains(b, a)
}
